"""Read the supplied workbook without changing it; emit an offline browser snapshot."""
import argparse
import collections
import datetime as dt
import hashlib
import json
from pathlib import Path
import openpyxl

parser = argparse.ArgumentParser()
parser.add_argument('workbook', type=Path)
args = parser.parse_args()
book = openpyxl.load_workbook(args.workbook, read_only=True, data_only=True)
sheet = book['osca_votes_rows']
rows = list(sheet.values)
assert rows[0] == ('house', 'candidate', 'voted_at'), 'Unexpected source columns'
events = []
for row, (house, candidate, timestamp) in enumerate(rows[1:], 2):
    assert house in 'OSCA' and isinstance(candidate, int)
    assert 1 <= candidate <= (4 if house == 'S' else 3), f'Invalid candidate at row {row}'
    time = dt.datetime.fromisoformat(timestamp)
    assert time.tzinfo, f'Missing timezone at row {row}'
    events.append([house, candidate, round(time.timestamp() * 1000)])
events.sort(key=lambda e: e[2])
counts = {h: [sum(e[0] == h and e[1] == c for e in events) for c in range(1, 5 if h == 'S' else 4)] for h in 'OSCA'}
assert counts == {'O': [207, 107, 77], 'S': [113, 93, 87, 97], 'C': [108, 138, 129], 'A': [132, 106, 140]}
data = {
    'version': 1,
    'source': {'filename': args.workbook.name, 'sha256': hashlib.sha256(args.workbook.read_bytes()).hexdigest(), 'sheet': sheet.title, 'records': len(events)},
    'online': events,
    'offline': {
        'magok': {'O': [270, 199, 108], 'S': [167, 132, 95, 184], 'C': [212, 184, 182], 'A': [218, 124, 233]},
        'sangam': {'O': [125, 149, 100], 'S': [81, 113, 87, 89], 'C': [110, 129, 131], 'A': [150, 105, 115]},
        'yongsan': {'O': [218, 201, 149], 'S': [115, 153, 145, 155], 'C': [198, 202, 168], 'A': [185, 151, 224]},
    },
    'excluded': [{'site': 'yongsan', 'house': 'C', 'candidate': 4, 'votes': 1}, {'site': 'yongsan', 'house': 'A', 'candidate': 4, 'votes': 10}, {'site': 'magok', 'house': 'A', 'candidate': 4, 'votes': 1}],
}
target = Path(__file__).resolve().parents[1] / 'votes.js'
target.write_text('/* Source snapshot; generated by tools/import-votes.py. */\nwindow.OSCA_VOTES = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
print(json.dumps({'records': len(events), 'online': counts, 'output': str(target)}, ensure_ascii=False))
